import type { MarkedText } from "$lib/learning/marked-text";

import type { FrequencyPartOfSpeech } from "./frequency/types";

export type EntryKind = "word" | "grammar" | "pronunciation";

export type WordOrigin = "curated" | "frequency";

export type WordRegister = "colloquial" | "slang";

export const REGISTER_CHIP_LABEL: Record<WordRegister, string> = {
  colloquial: "Colloquial",
  slang: "Slang",
};

export function isWordRegister(value: string | undefined | null): value is WordRegister {
  return value === "colloquial" || value === "slang";
}

/**
 * Grammatical gender of a noun lemma (a property of the word, not of a person).
 * Masculine splits by animacy; pluralia tantum (nohavice, dvere) get their own value.
 */
export type NounGender =
  "masculine-animate" | "masculine-inanimate" | "feminine" | "neuter" | "plural-only";

export const NOUN_GENDERS: readonly NounGender[] = [
  "masculine-animate",
  "masculine-inanimate",
  "feminine",
  "neuter",
  "plural-only",
];

/** English label (shown) + Slovak grammar term (shown beside / on hover). */
export const NOUN_GENDER_LABEL: Record<NounGender, { english: string; slovak: string }> =
  {
    "masculine-animate": { english: "masculine (animate)", slovak: "mužský rod životný" },
    "masculine-inanimate": {
      english: "masculine (inanimate)",
      slovak: "mužský rod neživotný",
    },
    feminine: { english: "feminine", slovak: "ženský rod" },
    neuter: { english: "neuter", slovak: "stredný rod" },
    "plural-only": { english: "plural only", slovak: "pomnožné podstatné meno" },
  };

export function isNounGender(value: string | undefined | null): value is NounGender {
  return NOUN_GENDERS.includes(value as NounGender);
}

/**
 * The gender a plural-only noun still has in dictionaries (dvere: feminine,
 * okuliare: masculine inanimate, ústa: neuter). Shown beside "plural only".
 */
export type PluralOnlyGender = Exclude<NounGender, "plural-only">;

export function isPluralOnlyGender(
  value: string | undefined | null,
): value is PluralOnlyGender {
  return isNounGender(value) && value !== "plural-only";
}

const PLURAL_ONLY_GENDER_ENGLISH: Record<PluralOnlyGender, string> = {
  "masculine-animate": "masculine animate",
  "masculine-inanimate": "masculine inanimate",
  feminine: "feminine",
  neuter: "neuter",
};

/** Label for an entry's gender: "plural only (feminine)" when the underlying gender is known. */
export function nounGenderLabel(
  gender: NounGender,
  pluralOnlyGender?: PluralOnlyGender,
): { english: string; slovak: string } {
  const label = NOUN_GENDER_LABEL[gender];
  if (gender !== "plural-only" || !pluralOnlyGender) return label;
  return {
    english: `${label.english} (${PLURAL_ONLY_GENDER_ENGLISH[pluralOnlyGender]})`,
    slovak: `${label.slovak}, ${NOUN_GENDER_LABEL[pluralOnlyGender].slovak}`,
  };
}

export const DIALECT_CHIP_LABEL = "Dialect";

export function dialectLookupFlag(value: { dialect?: unknown }): { dialect?: true } {
  return value.dialect === true ? { dialect: true as const } : {};
}

/**
 * One learner sentence under a lemma.
 * Hand-authoring rules (counts, notes, quality): `content/dictionary/README.md`.
 */
export interface Example {
  /** Short cue for pattern lemmas (e.g. "byť + location — where"). */
  demonstrates?: string;
  english: string;
  /** `"Curated"` | `"Tatoeba"` | other short attribution. */
  note?: string;
  practiceItemId?: string;
  slovak: string;
  /** Tatoeba sentence id for the Slovak side when note is "Tatoeba". */
  tatoebaId?: number;
}

export interface WordFrequency {
  partOfSpeech: FrequencyPartOfSpeech;
  rank: number;
}

/** Six case forms in order: nominative, genitive, dative, accusative, locative, instrumental. */
export type CaseForms = readonly [string, string, string, string, string, string];

/**
 * Hand-verified noun paradigm (checked against JÚĽŠ). Never generated by rule —
 * leave unset rather than guess a form.
 */
export interface NounDeclension {
  plural: CaseForms;
  singular: CaseForms;
}

/**
 * Runtime dictionary / grammar / pronunciation entry.
 * Hand-authored lemmas use only the `WordSeed` fields (slug, slovak, english,
 * category, examples, related, topics?, register?, gender?, pluralOnlyGender?, dialect?, declension?) —
 * see `content/dictionary/README.md`.
 * `origin`, `frequency`, `body`, `summary`, `tags`, and source* are filled in `data.ts`.
 */
export interface ContentEntry {
  aliases?: string[];
  body: string[];
  /**
   * Dictionary browse bucket: `Verbs` | `Nouns` | `Adjectives` | `Adverbs` | `Places` | `Phrases`.
   * Learner themes (Food, Greetings, …) live in `topics`, not here.
   */
  category: string;
  /** Nouns only: full case paradigm, shown as the Forms section. */
  declension?: NounDeclension;
  english: string;
  examples: Example[];
  /** Present when the lemma appears in an SNK top-1000 list. */
  frequency?: WordFrequency;
  kind: EntryKind;
  /** How this word entered the live dictionary. */
  origin?: WordOrigin;
  /** Existing lemma slugs only — never free-text labels. */
  related: string[];
  /** URL id from `lemmaToSlug(slovak)`; unique across curated seed + words.json. */
  slug: string;
  /** Lemma with correct Slovak diacritics. */
  slovak: string;
  source: string;
  /** Visible attribution label for the Source section. Falls back in UI when omitted. */
  sourceLabel?: string;
  sourceNote?: string;
  summary: string;
  tags: string[];
  /**
   * Optional learner themes for a future Essentials page (Food, Greetings, …).
   * Not used as dictionary browse chips.
   */
  topics?: string[];
  /** Spoken/informal register — Colloquial or Slang chip. */
  register?: WordRegister;
  /** Nouns only: grammatical gender (`assign-noun-gender.ts`). Unset when unresolved. */
  gender?: NounGender;
  /** With `gender: "plural-only"`: the gender dictionaries give the noun (dvere: feminine). */
  pluralOnlyGender?: PluralOnlyGender;
  /** Regional / non-standard variety — Dialect chip + Nárečie.sk lookup. */
  dialect?: true;
}

export interface GrammarTableRow {
  label: string;
  /** One per column. Wrap the ending in brackets (`moj[ej]`) when it does not extend the first cell. */
  cells: string[];
}

interface GrammarPatternShared {
  label: string;
  /** One or two sentences under the heading. Rich text: `**form**`, `[text](/path)`. */
  intro?: string;
}

/** Labelled lines, verb paradigms, and arrow rows. */
export interface GrammarLinePattern extends GrammarPatternShared {
  lines: string[];
}

/** A table. Cells are data, not a comma-split string. */
export interface GrammarTablePattern extends GrammarPatternShared {
  /** Heading over the row labels (Meaning, Person, Gender), so every column has one. */
  rowLabel: string;
  columns: string[];
  rows: GrammarTableRow[];
}

export type GrammarPattern = GrammarLinePattern | GrammarTablePattern;

/** A further table, with the sentences that show it. The main table's are the topic's `examples`. */
export type GrammarMorePattern = GrammarPattern & { examples?: Example[] };

/** A grammar label in English and in the Slovak school term (nominatív, mužský rod životný). */
export interface GrammarTerm {
  en: string;
  sk: string;
}

/** The small drawing beside each sentence of a contrast frame. */
export type GrammarScene =
  "space" | "time" | "owner" | "gender" | "address" | "aspect" | "past" | "clock";

/** The thing the frame talks about, drawn in the scene where the sentence puts it. */
export type GrammarObject =
  | "shirt"
  | "book"
  | "shoes"
  | "people"
  | "dog"
  | "children"
  | "house"
  | "keys"
  | "person";

/**
 * What the scene highlights for one sentence: where the thing is (`me`, `them`,
 * `far`), when (`now`, `before`), who owns it (`own`, `other`; `his`, `hers`), who you talk to
 * (`friend`, `formal`, `group`), how the action runs (`now`, `ongoing`, `done`,
 * `habit`; the `past` scene draws them before now), or a clock time against a
 * length of time (`clock`, `span`).
 */
export type GrammarCue =
  | "me"
  | "them"
  | "far"
  | "now"
  | "before"
  | "own"
  | "other"
  | "his"
  | "hers"
  | "friend"
  | "formal"
  | "group"
  | "ongoing"
  | "done"
  | "habit"
  | "clock"
  | "span";

/** One way to fill the frame, and the situation that calls for it. */
export interface GrammarChoice {
  /** What the frame's scene highlights for this sentence. */
  at?: GrammarCue;
  english: string;
  /** Spoken Slovak, with the word that changes marked. */
  slovak: MarkedText;
  /** The situation in a few words: “in your hand”. */
  when: string;
  /** What picks the form, at the row's right edge: “Owner is the subject: **svoj**”. */
  why?: string;
}

/** One sentence said two or three ways; the situation picks the form. */
export interface GrammarContrast {
  choices: GrammarChoice[];
  /** Case, gender and number the frame shows, in the school terms of both languages. */
  label?: GrammarTerm;
  object?: GrammarObject;
  /** The question the learner asks first: “Where is the shirt?” */
  question: string;
  scene?: GrammarScene;
}

export interface GrammarContrastSet {
  /** The choice the learner faces: “Tento, ten, or tamten?” */
  label: string;
  intro?: string;
  frames: GrammarContrast[];
  /** The same choice in further cases, folded until opened. */
  more?: GrammarContrast[];
}

/** A form learners get wrong, the form to use, and a few words on why. */
export interface GrammarMistake {
  right: string;
  why: string;
  wrong: string;
}

/** A short tip (`**form**` bolds Slovak), or a mistake to avoid. */
export type GrammarWatchOut = string | GrammarMistake;

/** In-page sections for gloss-term deep links (e.g. #imperfective). */
export interface GrammarTermSection {
  /** `**form**` marks Slovak to notice. */
  body: string;
  /** Short Slovak phrases that show the label at work. */
  examples?: string[];
  /** English name, when `term` is the Slovak one. */
  gloss?: string;
  id: string;
  term: string;
}

export interface CaseReference {
  explanation?: string;
  name: string;
  question?: string;
  researchPrompt?: string;
  role?: string;
  slug: string;
}

export interface CaseTopic {
  body: string[];
  examples: Example[];
  /** Endings on four reference nouns, singular and plural. */
  forms?: GrammarTablePattern;
  name: string;
  /** Slovak grammar term for the case (genitív). */
  slovakName: string;
  question: string;
  researchPrompts: string[];
  slug: string;
  source: string;
  status: "draft" | "ready";
  summary: string;
}

export interface GrammarTopic extends ContentEntry {
  caseOverview?: CaseReference[];
  /** Minimal pairs that show when to pick each form. */
  contrasts?: GrammarContrastSet;
  kind: "grammar";
  lookFor: string;
  lessonLink?: {
    href: string;
    label: string;
  };
  nextSlug?: string;
  order: number;
  pathGroup: "Nouns" | "Verbs" | "Sentence building" | "Numbers";
  pattern: GrammarPattern;
  /** Further tables on the same page, each with its own heading. */
  morePatterns?: GrammarMorePattern[];
  rule: string[];
  /** Optional deep-link sections for dictionary gloss term tips. */
  termSections?: GrammarTermSection[];
  watchOut: GrammarWatchOut[];
}

export interface PronunciationContrast {
  left: string;
  note: string;
  right: string;
}

export interface PronunciationTopic extends ContentEntry {
  kind: "pronunciation";
  contrasts: PronunciationContrast[];
  goal: string;
  mouthCue: string;
  nextSlug?: string;
  order: number;
  pathGroup: "Rhythm" | "Vowels" | "Consonants" | "Spelling";
  practicePhrase: Example;
  practiceWords: string[];
}
